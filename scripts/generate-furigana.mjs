// Generates furigana annotations for Japanese copy at build time.
// Run with: npm run furigana:generate
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const esbuild = require(require('path').resolve('node_modules/vite/node_modules/esbuild'))
const kuromoji = require('kuromoji')
const path = require('path')
const fs = require('fs')

function loadTs(file) {
  const code = esbuild.transformSync(fs.readFileSync(file, 'utf8'), {
    loader: 'ts',
    format: 'cjs',
  }).code
  const module = { exports: {} }
  new Function('module', 'exports', code)(module, module.exports)
  return module.exports.default || module.exports
}

function toHiragana(value) {
  return value.replace(/[\u30A1-\u30F6]/g, (char) =>
    String.fromCharCode(char.charCodeAt(0) - 0x60),
  )
}

const hasKanji = (value) => /[一-龯々]/.test(value)
const { linkParts } = loadTs('src/utils/links.ts')

const overrides = {
  読: 'どく',
  枚: 'まい',
  年: 'ねん',
  月: 'がつ',
  日: 'にち',
}

const extraSamples = [
  '2026年3月27日',
  '2025年5月19日',
  '1,501枚 · 46日連続 · 今日1枚',
  'Ankiから同期（2026/11/21）',
]

const dictionary = loadTs('src/i18n/ja.ts')
const strings = new Set(extraSamples)

function collect(value) {
  if (typeof value === 'string') {
    if (!value) return
    strings.add(value)
    for (const part of linkParts(value)) strings.add(part.text)
  } else if (value && typeof value === 'object') {
    Object.values(value).forEach(collect)
  }
}
collect(dictionary)

const tokenizer = kuromoji.builder({
  dicPath: path.resolve('node_modules/kuromoji/dict'),
})

const built = await new Promise((resolve, reject) => {
  tokenizer.build((error, result) => {
    if (error) reject(error)
    else resolve(result)
  })
})

const generated = {}
const tokenReadings = {}

for (const text of [...strings].sort()) {
  if (!hasKanji(text)) continue
  const parts = built.tokenize(text).map((token) => {
    const surface = token.surface_form
    const raw = token.reading || ''
    const reading = overrides[surface]
      || (hasKanji(surface) && raw && raw !== surface ? toHiragana(raw) : '')
    if (reading && hasKanji(surface) && !tokenReadings[surface]) {
      tokenReadings[surface] = reading
    }
    return { text: surface, reading }
  })
  if (parts.some((part) => part.reading)) generated[text] = parts
}

const kanjiChars = new Set()
for (const text of strings) {
  for (const char of text) if (hasKanji(char)) kanjiChars.add(char)
}
for (const char of kanjiChars) {
  const token = built.tokenize(char).find((item) => item.surface_form === char && item.reading)
  if (token && !tokenReadings[char]) tokenReadings[char] = toHiragana(token.reading)
}

for (const [surface, reading] of Object.entries(overrides)) {
  tokenReadings[surface] = reading
}

const output = `// Generated by scripts/generate-furigana.mjs. Do not edit by hand.\n` +
  `export const furiganaGenerated: Record<string, { text: string; reading: string }[]> = ${JSON.stringify(generated, null, 2)}\n\n` +
  `export const furiganaTokens: Record<string, string> = ${JSON.stringify(tokenReadings, null, 2)}\n`

fs.writeFileSync('src/data/furigana.generated.ts', output)
console.log(`generated ${Object.keys(generated).length} entries and ${Object.keys(tokenReadings).length} token readings`)
